# 안 그러면 방금 없애기로 한 이름을 드롭다운이 다시 권한다.
LEGACY_ALIASES = {
    'TDF Fund',                 # → '연금 (TDF)'
    '자산배분 (개별주+채권)',
    '자산배분 (빅테크+채권)',
    '자산배분 (지수+채권)',
}


def labels_by_group() -> dict:
    out = {g: [] for g in SECTOR_GROUPS}
    for label, group in LABEL_TO_GROUP.items():
        if label in LEGACY_ALIASES:
            continue
        out.setdefault(group, []).append(label)
    return {g: sorted(v) for g, v in out.items() if v}


def sector_group(label: str) -> str:
    """중분류 라벨 → 대분류. 모르는 라벨은 접두어로 한 번 더 시도한 뒤 '기타'."""
    s = (label or '').strip()
    if not s:
        return '기타'
    if s in LABEL_TO_GROUP:
        return LABEL_TO_GROUP[s]
    # '반도체 (신규테마)' 처럼 아직 등록 안 된 중분류는 앞머리로 묶어 준다
    head = s.split('(')[0].strip()
    if head in LABEL_TO_GROUP:
        return LABEL_TO_GROUP[head]
    for g in SECTOR_GROUPS:
        if head == g or s.startswith(g):
            return g
    return '기타'


def unknown_labels(labels) -> list:
    """등록되지 않은 라벨 목록 — 월 1회 점검·신규 등록 유도에 쓴다."""
    return sorted({l for l in labels
                   if (l or '').strip() and (l or '').strip() not in LABEL_TO_GROUP})
