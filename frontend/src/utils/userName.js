/* ══════════════════════════════════════════════════════════════
   화면에 쓰는 사용자 이름 — 한 곳에서만 정한다
   ══════════════════════════════════════════════════════════════
   2026-09-10, 오너가 밝힌 적 없는 실명이 화면 오른쪽 위에 떠 있었다.
   동료도 자기 이름이 떠서 놀랐다고 했다.

   경로는 이랬다.
     ① 2026-06 상용 배포 때 가입 폼에 '이름 / 홍길동' 칸이 생겼다.
        그렇게 물으면 사람은 실명을 적는다.
     ② 그 값은 users.name 에 저장됐다.
     ③ 나중에 닉네임(users.nickname)이 생겼지만 화면마다 따로 골라 썼다.
        보유 탭은 nickname, 사이드바는 nickname || name, 상단 바는 name.
        한 곳만 실명을 찍어도 실명은 노출된다.

   그래서 고르는 규칙을 여기 하나로 모은다. 화면은 이 함수만 부른다.
   name 은 **절대 반환하지 않는다** — 실명일 수 있기 때문이다.

   ⚠ 종목 표시명은 utils/displayName.js 다. 이름이 비슷하니 헷갈리지 말 것 —
     저쪽은 티커·종목명, 이쪽은 사람이다.
   ══════════════════════════════════════════════════════════════ */

/** 사용자 객체 → 화면에 찍어도 되는 이름. 실명은 절대 나오지 않는다. */
export function displayNameOf(user) {
  const nick = String(user?.nickname || '').trim()
  if (nick) return nick
  // 닉네임을 아직 안 정한 계정 — 이메일 앞부분으로 대신한다.
  // 본인이 고른 문자열이고, 실명이 아니며, 설정에서 바꿀 수 있다.
  const local = String(user?.email || '').split('@')[0].trim()
  return local || '투자자'
}
