/* ══════════════════════════════════════════════════════════════
   투자의견 어휘 — 매수 / 중립 / 매도
   ══════════════════════════════════════════════════════════════
   2026-08-27 이전에는 Hold 를 '보유' 라고 썼다. 그런데 보유하지 않은 종목의
   분석에도 '보유' 가 찍히니 "사서 들고 있으라는 뜻인가?" 로 읽혔다.
   실제 의미는 '지금 사거나 팔 이유가 뚜렷하지 않다' 이다.

   ── 왜 '중립' 인가 ──
   증권업계 표준 3분류는 Buy / Hold / Sell 이고, 국내 표기는 매수 / 중립 / 매도다.
   '유보' 는 '의견 유보 = 의견을 내지 않음' 이라는 다른 뜻이라 등급명으로 쓰면
   "분석을 못 했다" 로 읽힌다. 등급은 세 가지가 맞고, 이름만 바로잡는다.

   ⚠ 캐시에 남아 있는 옛 '보유' 를 그대로 보여주면 두 표기가 섞인다.
     화면에 찍기 전에 normalizeReco() 를 통과시킨다.
   ══════════════════════════════════════════════════════════════ */

const ALIASES = {
  '보유': '중립', '유지': '중립', '홀드': '중립',
  'hold': '중립', 'buy': '매수', 'sell': '매도',
  'strongbuy': '강력매수', 'strongsell': '강력매도',
}

export function normalizeReco(v) {
  const t = String(v || '').trim()
  return ALIASES[t.toLowerCase()] || ALIASES[t] || t
}

/* 등급별 색 — R1(좌측 색띠 금지) 때문에 글자·테두리 색으로만 쓴다 */
export function recoColor(v) {
  const t = normalizeReco(v)
  if (t.includes('매수')) return 'var(--clr-pos-dark)'
  if (t.includes('매도')) return 'var(--clr-neg-dark)'
  return '#F59E0B'          // 중립
}

